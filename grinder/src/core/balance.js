// ── 곡선 함수 (설계 시트를 만든 것과 같은 식) ──────────────

/** 레벨 n 에 도달하는 데 필요한 경험치. */
export function expForLevel(n) {
  const l = BALANCE.레벨;
  return l.필요EXP_기울기 * n + l.필요EXP_절편;
}

/** 챕터 ch 까지의 누적 난이도 배율. 감쇠가 들어간다. */
export function chapterMult(ch, baseMult, decay) {
  let m = 1;
  for (let k = 1; k < ch; k++) m *= 1 + (baseMult - 1) * Math.pow(decay, k - 1);
  return m;
}

/** 챕터 ch, 스테이지 st 의 적 최대 체력. */
export function enemyHp(ch, st) {
  const c = BALANCE.챕터;
  let hp = c.적HP_기준값 * chapterMult(ch, c.적HP_챕터배율, c.적HP_챕터배율_감쇠);
  hp *= 1 + c.적HP_스테이지증가율 * (st - 1);
  if (st === c.보스_스테이지) hp *= c.보스_HP배율;
  return Math.round(hp);
}

/** 챕터 ch, 스테이지 st 의 적 공격력. */
export function enemyAtk(ch, st) {
  const c = BALANCE.챕터;
  let atk = c.적공격력_기준값 * chapterMult(ch, c.적공격력_챕터배율, c.적공격력_챕터배율_감쇠);
  atk *= 1 + c.적공격력_스테이지증가율 * (st - 1);
  if (st === c.보스_스테이지) atk *= c.보스_공격력배율;
  return Math.round(atk * 10) / 10;
}

/** 보스 스테이지인가. */
export function isBoss(st) {
  return st === BALANCE.챕터.보스_스테이지;
}

/** 전투력. 설계 시트 07_Power 와 같은 식. */
export function power({ atk = 0, hp = 0, armor = 0, skillLevels = 0, talentNodes = 0 }) {
  const w = BALANCE.Power;
  return Math.round(
    atk * w.ATK_가중치 + hp * w.HP_가중치 + armor * w.보호막_가중치
    + skillLevels * w.스킬레벨_가중치 + talentNodes * w.탤런트노드_가중치
  );
}
